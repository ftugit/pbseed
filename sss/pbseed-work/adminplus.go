package main

import (
	"github.com/pocketbase/pocketbase/core"
)

// adminplus.go — «админ+»: защищённый первый админ.
//
// «Админ+» — запись `users` с ролью «admin», созданная раньше всех
// остальных админов (среди живых записей; мягко удалённые не
// считаются). При совпадении времени создания разбор идёт по
// идентификатору — выбор детерминирован. Если первого админа
// понижают, стирают или удаляют, звание переходит к следующему по
// дате создания админу: защита всегда у самого раннего из живых.
//
// Исключения для «админ+» собраны в этом файле и точечно вшиты в
// защиту полей (см. protectUsersFields):
//
//   - бан через REST запрещён всем, кроме суперюзера (консоль тоже
//     не ограничена — оператор выше ролевой иерархии);
//   - роль «админ+» нельзя изменить через REST никому, кроме
//     суперюзера (иначе защиту обходили бы связкой «понизить, потом
//     забанить»);
//   - только «админ+» среди ролевых админов может повышать до
//     «admin» (суперюзер и консоль — как прежде).
//
// Будущие исключения добавляйте через `isAdminPlus`/`firstAdminID`:
// одно место определения, кто является первым админом.

// adminPlusCandidates — сколько самых ранних админов читать при
// поиске первого живого (запас на мягко удалённых в начале списка).
const adminPlusCandidates = 32

// firstAdminRecord возвращает первого админа — живую запись с ролью
// «admin» и самой ранней датой создания. Время — стоковое поле
// `created` коллекции пользователей (служебные коллекции используют
// свои `created_at`, у `users` оно не менялось).
//
// Параметры:
//   - app: core.App — приложение PocketBase.
//
// Возвращает: *core.Record — первый админ или nil, если админов нет.
func firstAdminRecord(app core.App) *core.Record {
	// Сортировка в языке запросов PB: поле без «-» — по возрастанию.
	rows, err := app.FindRecordsByFilter("users", `role = {:role}`, "created, id",
		adminPlusCandidates, 0, map[string]any{"role": seedRoleAdmin})
	if err != nil {
		return nil
	}
	for _, r := range rows {
		if !isSoftDeleted(r) {
			return r
		}
	}
	return nil
}

// firstAdminID возвращает идентификатор первого админа.
//
// Параметры:
//   - app: core.App — приложение PocketBase.
//
// Возвращает: string — ид или пустая строка, если админов нет.
func firstAdminID(app core.App) string {
	if r := firstAdminRecord(app); r != nil {
		return r.Id
	}
	return ""
}

// isAdminPlus сообщает, является ли пользователь «админом+» — первым
// админом по дате создания. Вычисляется на каждое обращение: звание
// переезжает при выбытии текущего носителя, кэшировать нельзя.
//
// Параметры:
//   - app: core.App — приложение PocketBase;
//   - u: *core.Record — проверяемая запись `users` (допускается nil).
//
// Возвращает: bool — совпадает ли запись с первым живым админом.
func isAdminPlus(app core.App, u *core.Record) bool {
	if u == nil {
		return false
	}
	return firstAdminID(app) == u.Id
}
